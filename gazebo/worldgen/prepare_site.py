#!/usr/bin/env python3
"""Startup step of the `worldgen` compose service: make sure the Gazebo site
world for the location in .env exists, and tell gazebo and autopilot to use it.

Reads (all from .env through compose):
  SITE_LAT, SITE_LON     site origin in decimal degrees. Both empty -> no site:
                         Gazebo loads its built-in iris_runway and SITL keeps
                         its default home.
  SITE_NAME              directory/world name (default: derived from lat/lon)
  SITE_RADIUS            half-size of the square world in metres (default 50)
  SITE_TERRAIN           1 = SRTM terrain relief, 0 = flat ground (default 1)
  SITE_EXTRA_ARGS        extra make_gz_world.py flags, e.g. "--no-ms-buildings"
  SITE_REGENERATE        1 = rebuild even if an up-to-date world exists
  SITES_DIR              where sites live (default /sites = ./gazebo/sites)
  ACTIVE_FILE            selection file written for gazebo/autopilot

The world is generated by make_gz_world.py (downloads imagery, elevation,
OpenStreetMap and Microsoft building data) only when it does not exist yet or
its inputs changed; otherwise the existing site is reused with no network
access. If generation fails but an older world for the same name exists, that
one is used with a warning, so a flaky network does not stop the simulator.

The selection file is plain KEY=VALUE lines, read with sed (never sourced):
  GZ_WORLD=/opt/gazebo/sites/<name>/worlds/<name>.sdf   (gazebo's path)
  SITL_HOME=<lat>,<lon>,<alt>,<heading>                 (site_info.json sitl_home)
Empty values select the built-in runway / SITL default home.
"""

import json
import os
import re
import shlex
import shutil
import sys
import traceback
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_gz_world  # noqa: E402

# Where gazebo sees the sites directory (compose mounts ./gazebo/sites there).
GAZEBO_SITES_DIR = "/opt/gazebo/sites"
MARKER = ".worldgen.json"


def env(name: str, default: str = "") -> str:
    return os.environ.get(name, "").strip() or default


def write_active(path: Path, world: str, home: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(f"GZ_WORLD={world}\nSITL_HOME={home}\n")
    tmp.replace(path)
    print(f"[worldgen] {path.name}: GZ_WORLD={world or '(built-in runway)'} "
          f"SITL_HOME={home or '(SITL default)'}")


def site_ready(site_dir: Path, name: str) -> bool:
    return (site_dir / "worlds" / f"{name}.sdf").is_file() and (site_dir / "site_info.json").is_file()


def main() -> int:
    sites_dir = Path(env("SITES_DIR", "/sites"))
    active = Path(env("ACTIVE_FILE", str(sites_dir / ".active")))
    lat_s, lon_s = env("SITE_LAT"), env("SITE_LON")

    if not lat_s and not lon_s:
        print("[worldgen] SITE_LAT/SITE_LON not set: using the built-in runway world")
        write_active(active, "", "")
        return 0
    try:
        lat, lon = float(lat_s), float(lon_s)
    except ValueError:
        print(f"[worldgen] SITE_LAT/SITE_LON must both be decimal degrees, got {lat_s!r}, {lon_s!r}")
        return 1
    if not (-90 <= lat <= 90 and -180 <= lon <= 180):
        print(f"[worldgen] SITE_LAT/SITE_LON out of range: {lat}, {lon}")
        return 1

    default_name = "site_" + f"{lat:.5f}_{lon:.5f}".replace("-", "m").replace(".", "p")
    name = env("SITE_NAME", default_name)
    if not re.fullmatch(r"[A-Za-z0-9_-]+", name):
        print(f"[worldgen] SITE_NAME may only contain letters, digits, '_' and '-': {name!r}")
        return 1

    gen_args = ["--lat", repr(lat), "--lon", repr(lon), "--radius", env("SITE_RADIUS", "50"),
                "--name", name]
    if env("SITE_TERRAIN", "1") not in ("0", "false", "no"):
        gen_args.append("--terrain")
    gen_args += shlex.split(env("SITE_EXTRA_ARGS"))

    site_dir = sites_dir / name
    marker = site_dir / MARKER
    try:
        previous = json.loads(marker.read_text())
    except (OSError, ValueError):
        previous = None

    up_to_date = site_ready(site_dir, name) and previous == {"args": gen_args}
    if up_to_date and env("SITE_REGENERATE") not in ("1", "true", "yes"):
        print(f"[worldgen] reusing {site_dir} (inputs unchanged; SITE_REGENERATE=1 rebuilds)")
    else:
        # Generate next to the final location and swap in only on success,
        # so a failed run never leaves a half-written world behind.
        work = sites_dir / f".{name}.tmp"
        shutil.rmtree(work, ignore_errors=True)
        print(f"[worldgen] generating {name} at {lat}, {lon}: make_gz_world.py {' '.join(gen_args)}")
        try:
            make_gz_world.main(gen_args + ["--out", str(work)])
            if not site_ready(work, name):
                raise RuntimeError("generator finished without a world file")
        except (Exception, SystemExit) as exc:  # noqa: BLE001 (generator may sys.exit)
            shutil.rmtree(work, ignore_errors=True)
            if isinstance(exc, SystemExit) and exc.code in (0, None):
                exc = RuntimeError("generator exited early")
            traceback.print_exc()
            if site_ready(site_dir, name):
                print(f"[worldgen] WARNING: generation failed ({exc}); "
                      f"falling back to the existing {site_dir}")
            else:
                print(f"[worldgen] generation failed ({exc}) and no earlier world exists; "
                      "gazebo will not start. Check network access, or clear SITE_LAT/SITE_LON "
                      "to use the built-in runway.")
                return 1
        else:
            (work / MARKER).write_text(json.dumps({"args": gen_args}, indent=2))
            shutil.rmtree(site_dir, ignore_errors=True)
            work.rename(site_dir)
            print(f"[worldgen] wrote {site_dir}")

    info = json.loads((site_dir / "site_info.json").read_text())
    write_active(active, f"{GAZEBO_SITES_DIR}/{name}/worlds/{name}.sdf", info["sitl_home"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
